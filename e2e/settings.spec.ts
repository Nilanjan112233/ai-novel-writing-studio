import { expect, test } from '@playwright/test'

test('AI settings expose real providers and the active Narrative Studio agents', async ({ page }) => {
  await page.goto('/settings')
  await expect(page.getByRole('heading', { name: 'AI Connections & Settings' })).toBeVisible()
  await expect(page.getByTestId('provider-card-gemini')).toBeVisible()
  await expect(page.getByTestId('provider-card-openrouter')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Validate Key' }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Discover Models' }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Verify Working Models' }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Test Selected Model' }).first()).toBeVisible()
  await expect(page.getByTestId('agent-assignment-table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Developer Mode' }).click()
  const assignments = page.getByTestId('agent-assignment-table')
  await expect(assignments).toBeVisible()
  await expect(page.locator('select#default-provider option[value="mock"]')).toHaveCount(0)
  await expect(assignments.locator('option[value="mock"]')).toHaveCount(0)
  await expect(assignments).toContainText('NarrativeDirectorAgent')
  await expect(assignments).toContainText('StoryArchitectAgent')
  await expect(assignments).toContainText('CharacterJourneyAgent')
  await expect(assignments).toContainText('WorldAgent')
  await expect(assignments).not.toContainText('IntakeAgent')
  await expect(assignments).not.toContainText('BrainstormAgent')
})
